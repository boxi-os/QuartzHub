#!/usr/bin/env node
// Golden file for FontDelivery, made by QuartzControl's own src/routes/Styles/fontDelivery.ts,
// fontSpec.ts (primaryFamily, summarizeFaces), previewFonts.ts (fontBuildState) and cssFixes.ts:
// which loaders fetch webfonts, the two switches, the translation of "Google, served from the
// project" on the way in and out, the build state the Basis tab warns about, the ready-made CSS
// fixes. Plain functions, so Node runs them; `t` answers `[[key]]`.
//
// The configs are gui-test's and Example's, and made-up ones over every combination that decides
// something: core's fontOrigin and cdnCaching, the Fonts plugin on, off and with its own
// fontOrigin, a theme plugin with and without its fonts, two of each.
//
// Also writes Sources/QuartzHubCore/Styles/GoogleFontList.swift from src/data/googleFonts.ts.
//
//   Runtime/node/bin/node scripts/font-delivery-golden.mjs [../QuartzControl] [~/Documents/QuartzProjekte]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadQuartzControl } from './lib/qc-bundle.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const control = resolve(process.argv[2] ?? join(here, '..', '..', 'QuartzControl'))
const projects = resolve(process.argv[3] ?? join(homedir(), 'Documents', 'QuartzProjekte'))
const core = join(here, '..', 'Packages', 'QuartzHubCore')
const out = join(core, 'Tests', 'QuartzHubCoreTests', 'Fixtures', 'font-delivery')
const yaml = createRequire(join(control, 'package.json'))('yaml')

const delivery = await loadQuartzControl(control, 'src/routes/Styles/fontDelivery.ts', {})
const spec = await loadQuartzControl(control, 'src/routes/Styles/fontSpec.ts', {})
const preview = await loadQuartzControl(control, 'src/routes/Styles/previewFonts.ts', {})
const fixes = await loadQuartzControl(control, 'src/routes/Styles/cssFixes.ts', {})
const fontsList = await loadQuartzControl(control, 'src/data/googleFonts.ts', {})

// ── the Google font list, for the app ───────────────────────────────────────────────────────────
const lines = fontsList.GOOGLE_FONTS.map(([family, category]) => {
  if (/[\t\n"\\]/.test(family)) throw new Error(`unexpected character in ${family}`)
  return `${family}\t${category}`
})
writeFileSync(join(core, 'Sources', 'QuartzHubCore', 'Styles', 'GoogleFontList.swift'), `// Generated by scripts/font-delivery-golden.mjs from QuartzControl's src/data/googleFonts.ts - do not
// edit by hand. Every family Google Fonts served on ${fontsList.GOOGLE_FONTS_FETCHED}, most popular first, with its category.
// A typing aid and a spelling check, not a gate: Quartz asks Google for whatever name is written.
extension GoogleFontList {
  static let fetched = "${fontsList.GOOGLE_FONTS_FETCHED}"
  static let table = """
${lines.join('\n')}
"""
}
`)

// ── configs ─────────────────────────────────────────────────────────────────────────────────────
const real = ['gui-test', 'Example'].map((name) => {
  const parsed = yaml.parse(readFileSync(join(projects, name, 'quartz.config.yaml'), 'utf8'))
  const { theme = {}, ...configuration } = parsed.configuration ?? {}
  return { name, config: { configuration, theme, plugins: parsed.plugins ?? [] } }
})

const FONTS = '@quartz-community/quartz-fonts'
const plugin = (source, enabled, options) => ({ source, enabled, ...(options === undefined ? {} : { options }) })
const made = []
const origins = [undefined, 'googleFonts', 'local', 'other']
const caching = [undefined, true, false]
const fontsPlugins = [[], [plugin(FONTS, true)], [plugin(FONTS, false)], [plugin(FONTS, true, { fontOrigin: 'selfHosted' })],
  [plugin(FONTS, true, { fontOrigin: 'googleFonts', other: 1 })], [plugin(FONTS, false, { fontOrigin: 'selfHosted' }), plugin(FONTS, true)]]
const themePlugins = [[], [plugin('@quartz-themes/minimal', true, { theme: 'minimal' })], [plugin('@quartz-themes/minimal', true, { theme: 'minimal', themeFonts: false })],
  [plugin('@quartz-themes/minimal', false, { theme: 'minimal' })], [plugin('@quartz-themes/core', true, { theme: 42 })],
  [plugin('@quartz-themes/a', false, { theme: 'a' }), plugin('@quartz-themes/b', true, { theme: 'b', themeFonts: true })], [plugin({ name: 'x' }, true)]]
for (const fontOrigin of origins) {
  for (const cdnCaching of caching) {
    for (const [fi, fp] of fontsPlugins.entries()) {
      for (const [ti, tp] of themePlugins.entries()) {
        if ((fi + ti) % 3 !== 0 && fontOrigin !== undefined) continue
        const theme = { typography: { header: 'Schibsted Grotesk', body: { name: 'Source Sans Pro', weights: [400] }, code: 'IBM Plex Mono' } }
        if (fontOrigin !== undefined) theme.fontOrigin = fontOrigin
        if (cdnCaching !== undefined) theme.cdnCaching = cdnCaching
        made.push({ name: `${fontOrigin}/${cdnCaching}/f${fi}/t${ti}`, config: { configuration: { pageTitle: 'x', baseUrl: fi === 3 ? '' : 'example.com' }, theme, plugins: [plugin('@quartz-community/explorer', true), ...fp, ...tp] } })
      }
    }
  }
}
const configs = [...real, ...made]

const blocks = ['', '/* --- QuartzControl:managed:google-fonts:start --- */', '/* --- Quartz-GUI:managed:google-fonts:start --- */',
  '/* --- quartzcontrol:managed:google-fonts:start --- */', '/* --- QuartzControl:managed:google-fonts:end --- */', '/* --- Quartz GUI:managed:google-fonts:start --- */',
  'x /* --- a_b-1:managed:google-fonts:start --- */ y']

const faceSets = {
  none: [],
  project: [{ family: 'Schibsted Grotesk', weight: '400', style: 'normal', origin: 'project', source: 'custom.scss' }],
  build: [{ family: 'schibsted grotesk', weight: '700', style: 'normal', origin: 'build', source: 'public/index.css' },
    { family: 'IBM Plex Mono', weight: '400', style: 'italic', origin: 'build', source: 'public/index.css' }],
  all: [{ family: 'Schibsted Grotesk', weight: '100 900', style: 'normal', origin: 'project', source: '_quartzcontrol.scss' },
    { family: 'Source Sans Pro', weight: '400', style: 'oblique 10deg', origin: 'theme', source: 'minimal' },
    { family: 'IBM Plex Mono', weight: '600', style: 'normal', origin: 'build', source: 'public/index.css' },
    { family: 'IBM Plex Mono', weight: ' 400 ', style: 'Italic', origin: 'project', source: 'x.scss' },
    { family: 'IBM Plex Mono', weight: 'bold', style: 'normal', origin: 'project', source: 'x.scss' }]
}

const t = (key) => `[[${key}]]`
const strip = (value) => JSON.parse(JSON.stringify(value === undefined ? null : value))
const result = configs.map(({ name, config }) => ({
  name,
  config,
  loaders: delivery.fontLoaders(config),
  callsGoogle: delivery.callsGoogle(config),
  themeFontsEnabled: delivery.themeFontsEnabled(config),
  withThemeFontsOn: strip(delivery.withThemeFonts(config, true)),
  withThemeFontsOff: strip(delivery.withThemeFonts(config, false)),
  selfHostedOn: strip(delivery.withSelfHostedFonts(config, true)),
  selfHostedOff: strip(delivery.withSelfHostedFonts(config, false)),
  fetchesGoogleFonts: delivery.fetchesGoogleFonts(config),
  persist: strip(delivery.persistFontDelivery(config)),
  present: blocks.map((block) => strip(delivery.presentFontDelivery(config, block))),
  buildState: Object.fromEntries(Object.entries(faceSets).map(([key, faces]) => [key, [null, true, false].map((built) => strip(preview.fontBuildState(config, faces, built)))])),
  fixes: fixes.CSS_FIXES.map((fix) => ({ id: fix.id, applies: fix.appliesTo(config) }))
}))

const stacks = ['Instrument, ui-sans-serif, system-ui', '"Schibsted Grotesk", sans-serif', "'IBM Plex Mono'", '', '  spaced  , x', '"half', undefined, ',', 'a"b"']
const summaries = ['Schibsted Grotesk', 'ibm plex mono', 'Source Sans Pro', 'nothing', ''].map((family) => ({ family, summary: strip(spec.summarizeFaces(faceSets.all, family)) }))

mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'cases.json'), JSON.stringify({
  configs: result,
  blocks,
  faceSets,
  primaryFamily: stacks.map((stack) => ({ stack: stack ?? null, family: spec.primaryFamily(stack) })),
  summaries,
  fixes: fixes.CSS_FIXES.map((fix) => ({ id: fix.id, fileName: fix.fileName, content: fix.content(t) })),
  googleFontsCount: fontsList.GOOGLE_FONTS.length
}) + "\n")
console.log(`${result.length} configs, ${fontsList.GOOGLE_FONTS.length} Google families`)
